function fixture(ids = ['n0', 'n1']) {
  const notes: ReadingNote[] = ['Listen first', 'Start small', 'Pause'].map((title, i) => ({ id: `n${i}`, sourceDraftId: `d${i}`, title, bookTitle: i ? 'Habits' : 'Communication', chapterTitle: 'Chapter', content: markdownToReadingNoteDocument(`內容 ${i}`), createdAt: 1, updatedAt: 1, revision: 1 }));
  let state: PracticeState = { version: 1, revision: 1, pins: ids.map((noteId, i) => ({ noteId, pinnedAt: i + 1 })) };
  const api: PracticeApi = { list: vi.fn(async () => structuredClone(state)), setPinned: vi.fn(async ({ noteId, pinned }) => { state = { ...state, revision: state.revision + 1, pins: pinned ? [...state.pins, { noteId, pinnedAt: 5 }] : state.pins.filter(p => p.noteId !== noteId) }; return structuredClone(state); }) };
  const notesApi = { list: vi.fn(async ({ status }) => notes.filter(n => status === 'trashed' ? n.trashedAt !== undefined : n.trashedAt === undefined)), get: vi.fn(async (id: string) => notes.find(n => n.id === id)), attachments: { readDataUrl: vi.fn(async () => 'data:image/png;base64,example') } } as unknown as ReaderDesktopApi['readingNotes'];
  return { api, notesApi, notes };
}
async function mount(f = fixture()) {
  const loader = modules['../src/renderer/PracticeWorkspace.tsx']; expect(loader, 'F45 needs a production practice page').toBeTypeOf('function');
  const { PracticeWorkspace: Workspace } = await loader() as { PracticeWorkspace: typeof PracticeWorkspace };
  const view = render(<Workspace api={f.api} notesApi={f.notesApi} />);
  await screen.findByRole('heading', { name: /Pinned Notes/ });
  return { ...f, ...view };
}
